  const SKIP_TAGS = new Set(["SCRIPT", "STYLE", "CODE", "PRE", "TEXTAREA"]);

  function translateString(value, dictionary) {
    const trimmed = value.trim();
    const translated = dictionary[trimmed];
    if (translated) return value.replace(trimmed, translated);

    const prefixMatch = trimmed.match(/^([^A-Za-z\u4e00-\u9fff]+)(.+)$/);
    if (prefixMatch && dictionary[prefixMatch[2]]) {
      return value.replace(trimmed, `${prefixMatch[1]}${dictionary[prefixMatch[2]]}`);
    }

    let phraseTranslated = value;
    for (const [pattern, replacement] of PHRASES) {
      phraseTranslated = phraseTranslated.replace(pattern, replacement);
    }
    return phraseTranslated;
  }

  function translateTextNode(node) {
    const raw = node.nodeValue;
    if (!raw || !raw.trim()) return;
    const translated = translateString(raw, TEXT);
    if (translated !== raw) node.nodeValue = translated;
  }

  function translateElement(element) {
    if (!(element instanceof Element) || SKIP_TAGS.has(element.tagName)) return;

    for (const attr of ["placeholder", "title", "aria-label"]) {
      const value = element.getAttribute(attr);
      if (!value) continue;
      let translated = translateString(value, PLACEHOLDERS);
      if (translated === value) {
        translated = translateString(value, TEXT);
      }
      if (translated !== value) element.setAttribute(attr, translated);
    }

    for (const child of element.childNodes) {
      if (child.nodeType === Node.TEXT_NODE) {
        translateTextNode(child);
      } else if (child.nodeType === Node.ELEMENT_NODE) {
        translateElement(child);
      }
    }
  }

